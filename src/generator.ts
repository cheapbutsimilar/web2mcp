function renderPackageJson(name: string): string {
  return (
    JSON.stringify(
      {
        name: `${name}-mcp`,
        version: "0.1.0",
        private: true,
        description: `Local MCP server for ${name}, generated by web2mcp`,
        type: "module",
        bin: { [`${name}-mcp`]: "dist/index.js" },
        scripts: { build: "tsc -p tsconfig.json", start: "node dist/index.js", typecheck: "tsc -p tsconfig.json --noEmit" },
        dependencies: { "@modelcontextprotocol/sdk": SDK_VERSION, zod: ZOD_VERSION },
        devDependencies: { "@types/node": "^22.10.0", typescript: "^5.9.0" },
        engines: { node: ">=18.17" },
      },
      null,
      2,
    ) + "\n"
  );
}

