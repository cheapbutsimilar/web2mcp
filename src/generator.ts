export function generate(opts: GenerateOptions): GenerateResult {
  const outDir = resolve(opts.outDir ?? "output/mcp-server");
  const name = opts.name ?? serverNameFor(opts.session.origin);
  const tools = analyzeSession(opts.session);
  if (tools.length === 0) {
    throw new Error(
      "No API requests found in the session. Interact with the site (search, open items, submit forms) while recording so web2mcp can capture XHR/fetch calls.",
    );
  }

  const entry = join(outDir, "dist", "index.js");
  const config = { mcpServers: { [name]: { command: "node", args: [entry] } } };
  const configSnippets = {
    claudeDesktop: JSON.stringify(config, null, 2),
    cursor: JSON.stringify(config, null, 2),
    claudeCode: `claude mcp add ${name} -- node ${entry}`,
  };

  const files: Record<string, string> = {
    "src/index.ts": renderIndex(opts.session, name, tools),
    "package.json": renderPackageJson(name),
    "tsconfig.json": TSCONFIG,
    ".env.example": renderEnvExample(opts.session, tools),
    ".gitignore": "node_modules/\ndist/\n.env\n",
    "README.md": renderReadme(opts.session, name, tools, configSnippets),
    "mcp-config.json": JSON.stringify(config, null, 2) + "\n",
    "web2mcp.tools.json": JSON.stringify({ generatedAt: new Date().toISOString(), source: opts.session.startUrl, tools }, null, 2) + "\n",
  };

  for (const [rel, content] of Object.entries(files)) {
    const file = join(outDir, rel);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  const written = Object.keys(files);
  if (opts.secretsPath && existsSync(opts.secretsPath)) {
    const envFile = join(outDir, ".env");
    if (!existsSync(envFile)) {
      copyFileSync(opts.secretsPath, envFile);
      chmodSync(envFile, 0o600);
      written.push(".env");
    }
  }

  return { outDir, name, tools, files: written, configSnippets };
}
