// zod code emission
// ---------------------------------------------------------------------------

export function zodFor(shape: Shape, depth = 0): string {
  if (depth > 3) return "z.any()";
  switch (shape.kind) {
    case "string":
      return "z.string()";
    case "integer":
      return "z.number().int()";
    case "number":
      return "z.number()";
    case "boolean":
      return "z.boolean()";
    case "array":
      return `z.array(${zodFor(shape.items, depth + 1)})`;
    case "object": {
      const entries = Object.entries(shape.props);
      if (!entries.length) return "z.record(z.any())";
      const props = entries.map(([k, v]) => `${JSON.stringify(k)}: ${zodFor(v, depth + 1)}.optional()`).join(", ");
      return `z.object({ ${props} }).passthrough()`;
    }
    default:
      return "z.any()";
  }
}

function zodForParam(p: ToolParam): string {
  let code = zodFor(p.shape);
  if (!p.required) {
    code += p.example !== undefined && exampleFits(p.example, p.shape) ? `.default(${JSON.stringify(p.example)})` : ".optional()";
  }
  return `${code}.describe(${JSON.stringify(p.description)})`;
}

/** Guard against defaults whose runtime type would not satisfy the emitted schema. */
function exampleFits(v: unknown, shape: Shape, depth = 0): boolean {
  if (depth > 3) return true;
  switch (shape.kind) {
    case "string":
      return typeof v === "string";
    case "integer":
      return typeof v === "number" && Number.isInteger(v);
    case "number":
      return typeof v === "number";
    case "boolean":
      return typeof v === "boolean";
    case "array":
      return Array.isArray(v) && v.every((x) => exampleFits(x, shape.items, depth + 1));
    case "object":
      return (
        !!v &&
        typeof v === "object" &&
        !Array.isArray(v) &&
        Object.entries(v as Record<string, unknown>).every(([k, x]) => !shape.props[k] || x === null || x === undefined || exampleFits(x, shape.props[k]!, depth + 1))
      );
    default:
      return true;
  }
}

