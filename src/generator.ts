export interface GenerateOptions {
  session: Session;
  /** Output directory (default `output/mcp-server`). */
  outDir?: string;
  /** Server name used in package.json and mcpServers config. */
  name?: string;
  /** Path to a secrets.env produced by `record --save-secrets`; copied to `<outDir>/.env`. */
  secretsPath?: string;
}

export interface GenerateResult {
  outDir: string;
  name: string;
  tools: ToolSpec[];
  files: string[];
  configSnippets: { claudeDesktop: string; cursor: string; claudeCode: string };
}

export function serverNameFor(origin: string): string {
  const u = new URL(origin);
  if (u.hostname === "localhost" || /^[\d.]+$/.test(u.hostname) || u.hostname.startsWith("[")) return `local-${u.port || "80"}`;
  const host = u.host.replace(/^www\./, "");
  return host.replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-|-$/g, "").toLowerCase() || "site";
}

