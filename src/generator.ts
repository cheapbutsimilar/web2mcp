function renderEnvExample(session: Session, tools: ToolSpec[]): string {
  const headers = [...new Set(tools.flatMap((t) => t.secretHeaders))];
  const queries = [...new Set(tools.flatMap((t) => t.secretQuery))];
  const cookies = tools.some((t) => t.usesCookies);
  const lines = [
    "# ⚠️  SECURITY WARNING",
    "# These values are YOUR logged-in browser credentials. Anyone holding them can act as you.",
    "#  - copy this file to .env (already git-ignored) and never commit or share it",
    "#  - tokens/cookies expire: re-run `web2mcp record` (or copy fresh values from DevTools) when calls return 401/403",
    "#  - the server only runs locally over stdio; it does not expose a network port",
    "",
    "# Override the recorded origin (e.g. staging)",
    `WEB2MCP_BASE_URL=${session.origin}`,
    "",
  ];
  if (cookies) lines.push("# Full Cookie header copied from the browser (DevTools → Network → request → Cookie)", "WEB2MCP_COOKIE=", "");
  for (const h of headers) lines.push(`# Value of the "${h}" request header`, `${headerEnvName(h)}=`, "");
  for (const q of queries) lines.push(`# Value of the "${q}" query parameter`, `${queryEnvName(q)}=`, "");
  lines.push(
    "# Optional: extra headers as JSON, e.g. {\"x-custom\":\"1\"}",
    "# WEB2MCP_EXTRA_HEADERS=",
    "# WEB2MCP_MAX_RESPONSE_CHARS=20000",
    "# WEB2MCP_TIMEOUT_MS=30000",
    "",
  );
  return lines.join("\n");
}

